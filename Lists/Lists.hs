getFirstItem :: [a] -> a
getFirstItem []    = error "getFirstItem: empty list"
getFirstItem (first:_) = first

getSecondItem :: [a] -> a
getSecondItem []     = error "getSecondItem: empty list"
getSecondItem [_]    = error "getSecondItem: list has only one item"
getSecondItem (_:second:_) = second

getBody :: [a] -> [a]
getBody []       = error "getBody: empty list"
getBody (_:body) = body


